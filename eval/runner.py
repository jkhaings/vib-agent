"""Eval scorecard runner over eval/cases/case_*.json. Phase 5.

run_cwru_suite() (Phase 3.5) is available now: it runs every case in
eval/cases/cwru/*.json through the deterministic pipeline under the
unvalidated `route` profile and writes outputs/cwru_results.md — the
citable "validated against CWRU" artifact. Per the Phase 3.5 integrity
rule, this function only *measures and reports*; it never adjusts
config/thresholds.json to make the pass bar pass.
"""

